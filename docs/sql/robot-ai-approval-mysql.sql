-- LightESB robot AI validation decision / approval event, MySQL 8.0+
-- Run as DBA before LightESB starts; the application account may then keep DML-only privileges.

CREATE TABLE IF NOT EXISTS ROBOT_AI_VALIDATION_DECISION (
    ID VARCHAR(32) NOT NULL,
    DECISION_ID VARCHAR(64) NOT NULL,
    INFERENCE_ID VARCHAR(128) NOT NULL,
    ROBOT_ID VARCHAR(128) NOT NULL,
    SITE_ID VARCHAR(128) NULL,
    COMMAND_ID VARCHAR(128) NOT NULL,
    CORRELATION_ID VARCHAR(128) NULL,
    CANDIDATE_DIGEST VARCHAR(64) NOT NULL,
    CANDIDATE_COMMAND_JSON TEXT NOT NULL,
    MODEL_KEY VARCHAR(128) NOT NULL,
    MODEL_NAME VARCHAR(128) NOT NULL,
    MODEL_VERSION VARCHAR(128) NOT NULL,
    POLICY_VERSION VARCHAR(128) NOT NULL,
    RISK_LEVEL VARCHAR(32) NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    APPROVAL_PROVIDER VARCHAR(128) NULL,
    APPROVAL_EVENT_ID VARCHAR(128) NULL,
    PROVIDER_DECISION_ID VARCHAR(128) NULL,
    APPROVER_ID VARCHAR(128) NULL,
    BOUND_COMMAND_ID VARCHAR(128) NULL,
    VERSION BIGINT NOT NULL DEFAULT 0,
    OBSERVED_AT TIMESTAMP(6) NOT NULL,
    RECEIVED_AT TIMESTAMP(6) NOT NULL,
    EXPIRES_AT TIMESTAMP(6) NOT NULL,
    APPROVED_AT TIMESTAMP(6) NULL,
    CONSUMED_AT TIMESTAMP(6) NULL,
    CREATE_TIME TIMESTAMP(6) NOT NULL,
    UPDATE_TIME TIMESTAMP(6) NOT NULL,
    DECISION_SUMMARY TEXT NULL,
    APPROVAL_SUMMARY TEXT NULL,
    PRIMARY KEY (ID),
    CONSTRAINT UK_ROBOT_AI_DECISION_ID UNIQUE (DECISION_ID),
    CONSTRAINT UK_ROBOT_AI_DECISION_INFERENCE UNIQUE (INFERENCE_ID),
    CONSTRAINT UK_ROBOT_AI_DECISION_COMMAND UNIQUE (ROBOT_ID, COMMAND_ID),
    INDEX IDX_ROBOT_AI_DECISION_STATUS (STATUS, EXPIRES_AT)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin;

CREATE TABLE IF NOT EXISTS ROBOT_AI_APPROVAL_EVENT (
    ID VARCHAR(32) NOT NULL,
    PROVIDER_NAME VARCHAR(128) NOT NULL,
    KEY_ID VARCHAR(128) NOT NULL,
    EVENT_ID VARCHAR(128) NOT NULL,
    RAW_BODY_DIGEST VARCHAR(64) NOT NULL,
    DECISION_ID VARCHAR(64) NULL,
    EVENT_STATUS VARCHAR(32) NOT NULL,
    OCCURRED_AT TIMESTAMP(6) NULL,
    RECEIVED_AT TIMESTAMP(6) NOT NULL,
    RESULT_SUMMARY TEXT NULL,
    CREATE_TIME TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (ID),
    CONSTRAINT UK_ROBOT_AI_APPROVAL_EVENT UNIQUE (PROVIDER_NAME, EVENT_ID),
    INDEX IDX_ROBOT_AI_APPROVAL_DECISION (DECISION_ID)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin;
